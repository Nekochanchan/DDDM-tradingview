export function generateHistory(basePrice: number, volatility: number = 0.015, points: number = 30, trend: number = 0.005) {
  const result = [];
  let currentPrice = basePrice * (1 - (trend * points) / 2);
  const now = new Date();
  
  for (let i = points; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = `${time.getHours().toString().padStart(2, '0')}:${time.getMinutes().toString().padStart(2, '0')}`;
    const changeFactor = 1 + (Math.random() - 0.48) * volatility + trend;
    currentPrice = Math.max(1, currentPrice * changeFactor);
    
    const high = currentPrice * (1 + Math.random() * 0.004);
    const low = currentPrice * (1 - Math.random() * 0.004);
    const open = low + Math.random() * (high - low);
    const close = low + Math.random() * (high - low);
    const volume = Math.floor(10000 + Math.random() * 90000);

    result.push({
      time: timeStr,
      price: Number(currentPrice.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume
    });
  }
  return result;
}

